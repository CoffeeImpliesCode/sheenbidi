/// Flags for the one C translation unit.
///
/// `-std=c90` pins the dialect to the level upstream actually builds and tests
/// this source at, rather than to whatever the compiler happens to default to.
/// All three of upstream's build systems say the same thing: `Makefile` passes
/// `-ansi -pedantic`, `.github/workflows/linux.yml` passes
/// `CMAKE_C_STANDARD=90` with `CMAKE_C_EXTENSIONS=OFF` and `-Dc_std=c89` to
/// meson. It is not cosmetic. `Source/API/SBBase.h` and
/// `Source/Core/ThreadLocalStorage.h` select their atomics and TLS backend from
/// `__STDC_VERSION__`, and the choice decides which headers get pulled in: at
/// C11 and above they take the `USE_C11_*` branches and `#include <stdatomic.h>`,
/// while below it they fall through to the compiler-builtin branches
/// (`__atomic_*` and `__thread`) that need no standard or platform header at
/// all. Pinning the dialect is what keeps that decision deterministic across
/// the six targets this package claims.
///
/// `-DSB_CONFIG_UNITY` is upstream's unity switch. It is what turns
/// `SB_INTERNAL` into `static` so the thirty-two included translation units merge
/// into one without a single name colliding, and it is what makes
/// `Source/SheenBidi.c` a translation unit at all.
///
/// `SB_CONFIG_EXPERIMENTAL_TEXT_API` is absent on purpose, and so is
/// `SB_CONFIG_ALLOW_NON_ATOMIC_FALLBACK`: forcing the non-atomic path on a
/// threaded target would make a data race compile cleanly. Both absences are
/// the configuration this package selects, upstream's own shipped default, and
/// both are absences on the translation line too; see the module comment.
const c_flags = [_][]const u8{
    "-std=c90",
    "-DSB_CONFIG_UNITY",
};

/// Which half of the DLL import/export pair a macro belongs on: `build` for the
/// C compile line, `consume` for the translation line.
const DllSide = enum { build, consume };

/// The one export mechanism SheenBidi has, and the two macros that drive it.
///
/// `Headers/SheenBidi/SBConfig.h:20-21` ships `SB_CONFIG_DLL_EXPORT` and
/// `SB_CONFIG_DLL_IMPORT` commented out, and
/// `Headers/SheenBidi/SBBase.h:30-42` reads them to decide what `SB_PUBLIC`
/// expands to. Upstream states the pairing for its own `BUILDING_DLL` case at
/// `CMakeLists.txt:123-127`: build the DLL with the export macro, hand
/// consumers the import macro.
///
/// Both macros are inert unless the target is Windows, because `SBBase.h`
/// reads them only under `_WIN32`. They are therefore defined from the
/// artifact kind and not from the target: a dynamic build on ELF defines
/// nothing that ELF reads, and a dynamic build on Windows defines exactly what
/// Windows reads. One decision, one place.
///
/// A static build needs neither: with both macros absent `SB_PUBLIC` expands to
/// nothing, which is what a static archive and a plain `extern` declaration
/// both want.
///
/// These are compiler flags, never an edit to a checked-in header, so selecting
/// an export mode cannot change a byte of upstream's source. The macro *name*
/// is returned rather than a ready-made `-D…` flag because the C compile line
/// and the translation line spell a definition differently:
/// `Module.addCMacro` and `Step.TranslateC.defineCMacro` each build their own.
fn dllMacro(linkage: std.builtin.LinkMode, comptime side: DllSide) ?[]const u8 {
    if (linkage != .dynamic) return null;
    return switch (side) {
        .build => "SB_CONFIG_DLL_EXPORT",
        .consume => "SB_CONFIG_DLL_IMPORT",
    };
}

