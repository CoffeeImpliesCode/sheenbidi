/// Everything one target needs: the facade module, and the C library when this
/// build owns one.
const Graph = struct {
    /// The facade, with `c` bound to the translated aggregate header.
    module: *std.Build.Module,
    /// Null in `-fsys=sheenbidi` mode, where the library comes from the system.
    artifact: ?*std.Build.Step.Compile,
    /// The translation step `module`'s `c` was bound from. A second facade for
    /// the same target reads this one rather than translating the same header
    /// again, so both facades declare the same things.
    translate_c: *std.Build.Step.TranslateC,
    /// The loader core every facade of this target shares, or null in a
    /// `-Druntime=true` graph, which owns no facade of its own. There is one
    /// core per build and not one per facade: `LoadSource` and `LoadError` are
    /// named by all of them, and two core modules would be two sets of those
    /// two types.
    rt_core: ?*std.Build.Module,
};

/// One target's worth of decisions.
const GraphOptions = struct {
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    /// The kind of library this graph builds out of this repository's own C.
    linkage: std.builtin.LinkMode,
    /// The kind of *installed* library `-fsys=sheenbidi` binds to. Separate
    /// from `linkage` because in that mode this graph builds nothing at all, so
    /// `linkage` would be describing an artifact that does not exist.
    /// Only the main graph sets it; a cross-target check always builds from the
    /// in-tree sources and reads nothing from the system.
    system_linkage: std.builtin.LinkMode = .dynamic,
    use_system: bool,
    /// Register `sheenbidi` and `c` in the package module set, which is what a
    /// dependent reaches through `dep.module("sheenbidi")`. The cross-target
    /// check needs the private form instead: modules are registered by name
    /// against the whole build, so registering the same two names once per
    /// cross target would leave only the last pair reachable and silently stop
    /// checking the rest.
    public: bool,
    /// Resolve the native symbols through the platform loader instead of
    /// linking the library. Orthogonal to `linkage`: this decides what the
    /// facade is bound to, never what is compiled or installed.
    runtime: bool,
    /// Where a program built from this graph's facade must find the shared
    /// object it links. See `Loader`. The default is the published facade's
    /// flavour, and a graph that publishes its module does not override it;
    /// only the private facade an installed program is built from passes
    /// `.install_tree`.
    loader: Loader = .build_cache,
    /// Reuse another graph's library, translation step and loader core instead
    /// of building this graph's own.
    ///
    /// A program that is both installed and run is compiled twice, once for
    /// each `Loader`, and the two compilations must be of one library rather
    /// than of two builds of the same sources. Only `build`'s default optimize
    /// mode sets it, and only when `needsBothLoaders` says the two flavours
    /// really do differ; every other graph builds its own.
    shared: ?*const Graph = null,
};

/// Builds the C library and the facade for one target.
fn addGraph(b: *std.Build, options: GraphOptions) Graph {
    // A second facade for the same target reuses the first graph's library
    // rather than compiling the same C a second time: the two flavours of a
    // program differ in one `-rpath`, and a program that is the same program
    // on both sides of that is the whole point.
    const reused = options.shared;
    var artifact: ?*std.Build.Step.Compile = null;

    if (reused) |previous| {
        artifact = previous.artifact;
    } else if (!options.use_system) {
        const c_mod = b.createModule(.{
            .target = options.target,
            .optimize = options.optimize,
            // libc, because the core includes <stddef.h>, <stdlib.h>,
            // <string.h> and, through <SheenBidi/SBBase.h>, <stdint.h>. It is
            // needed in both linkages and is not a consequence of either.
            .link_libc = true,
            // Position independent code only for the shared library. A static
            // archive keeps the codegen it has always had, and a shared object
            // says so rather than leaving it to whatever the compiler driver
            // infers from the output mode. There is no visibility flag to
            // balance this with: `Headers/SheenBidi/SBBase.h:30-42` gives
            // `SB_PUBLIC` no `visibility("default")` arm, so
            // `-fvisibility=hidden` would hide the public entry points too and
            // the shared object would export nothing. See the module comment.
            .pic = if (options.linkage == .dynamic) true else null,
        });
        // `Headers` answers the <SheenBidi/...> includes; `Source` answers the
        // <API/...>, <Core/...>, <Data/...>, <Script/...>, <Text/...> and
        // <UBA/...> includes that the unity unit performs with angle brackets.
        c_mod.addIncludePath(b.path("Headers"));
        c_mod.addIncludePath(b.path("Source"));
        c_mod.addCSourceFile(.{
            .file = b.path(core_source),
            .flags = &c_flags,
        });
        // The build half of the export decision, on the C compile line and only
        // here. `SB_PUBLIC` is empty without it, so a DLL would export nothing.
        if (dllMacro(options.linkage, .build)) |macro_name| {
            c_mod.addCMacro(macro_name, "");
        }

        const lib = b.addLibrary(.{
            .name = library_name,
            .linkage = options.linkage,
            .root_module = c_mod,
            // The SONAME and the compatibility names upstream's own install
            // produces (`CMakeLists.txt:143-147`). Only meaningful for a shared
            // library: `addLibrary` ignores it for a static one, and on Windows
            // it is the import library name, which is `SheenBidi.lib` either
            // way. `-lSheenBidi` resolves against the plain name, which is the
            // symlink this version creates.
            .version = if (options.linkage == .dynamic) upstream.version else null,
        });
        // Installing the headers also puts them on the include search path of
        // anything that links this artifact, so a dependent that wants the C
        // API does not have to reach into this repository's tree for it.
        lib.installHeadersDirectory(b.path(public_header_source), public_header_dest, .{});
        artifact = lib;
    }

    const translate_c = if (reused) |previous| previous.translate_c else translate: {
        const translate_c = b.addTranslateC(.{
            .root_source_file = b.path("zig/translate.h"),
            .target = options.target,
            .optimize = options.optimize,
            .link_libc = true,
        });
        if (options.use_system) {
            // No bundled include path, so <SheenBidi/SheenBidi.h> resolves to the
            // installed header. pkg-config is asked first because the installed
            // `.pc` carries both the `-I` for a non-standard prefix and the
            // capitalised `-lSheenBidi`; without it the plain library name is
            // still right, because that is the name upstream installs.
            //
            // That file is one `zig build` produces. `addPkgConfig` writes
            // `lib/pkgconfig/SheenBidi.pc`, whose base name is `library_name` —
            // the same string `linkSystemLibrary` is asked for below — so a
            // `-fsys=sheenbidi` build with `PKG_CONFIG_PATH` naming this graph's
            // own install prefix resolves against the tree it was pointed at
            // rather than against whatever prefix the file was written with.
            //
            // The consume half of the export decision goes on this line, because
            // this is where a consumer's view of the installed headers is decided:
            // with `SB_CONFIG_DLL_IMPORT` the declarations are the ones a DLL
            // provides, and it is defined exactly when the linker below is asked
            // for a dynamic library, so the decoration and the library cannot end
            // up describing two different things.
            if (dllMacro(options.system_linkage, .consume)) |macro_name| {
                translate_c.defineCMacro(macro_name, "1");
            }
            // The link is the one thing a runtime build must not do. A dispatch
            // that also carried `-lSheenBidi` would have the linker resolve every
            // symbol before `load` ever runs, and the runtime route would be a
            // linked one wearing another name. `runtime/graph.zig:25-30` says the
            // same about the graph; this is the line that has to honour it.
            if (!options.runtime) {
                translate_c.linkSystemLibrary(library_name, .{
                    .use_pkg_config = .force,
                    .preferred_link_mode = options.system_linkage,
                });
            }
        } else {
            translate_c.addIncludePath(b.path("Headers"));
            // The bundled counterpart of the block above, following this graph's own
            // linkage: the declarations the facade reads are the ones the artifact
            // this repository just compiled answers to. `zig/translate.h` defines no
            // `SB_CONFIG_*` macro of its own, so each is defined exactly once and on
            // exactly one command line.
            if (dllMacro(options.linkage, .consume)) |macro_name| {
                translate_c.defineCMacro(macro_name, "1");
            }
        }
        break :translate translate_c;
    };
    // The `c` the facade is bound to. A runtime build replaces the translation
    // with a dispatch generated from that same translation step's output, so the
    // declarations the facade sees are still the ones this build selected and
    // only the arrival of the symbols changes. The dispatch is a private module
    // and cannot be re-registered under the graph name `c`, so `dep.module("c")`
    // exists in a linked build only - which is the name `zig/root.zig` itself
    // calls wiring rather than a second supported import.
    const raw = if (options.runtime)
        runtime_graph.createModule(b, translate_c, options.target, options.optimize)
    else if (options.public)
        translate_c.addModule("c")
    else
        translate_c.createModule();

    const facade = if (options.public)
        b.addModule("sheenbidi", .{
            .root_source_file = b.path("zig/root.zig"),
            .target = options.target,
            .optimize = options.optimize,
            .link_libc = true,
        })
    else
        b.createModule(.{
            .root_source_file = b.path("zig/root.zig"),
            .target = options.target,
            .optimize = options.optimize,
            .link_libc = true,
        });
    facade.addImport("c", raw);
    var rt_core: ?*std.Build.Module = null;
    if (options.runtime) {
        // No native link, and deliberately no `rt` import either. The dispatch
        // owns the one core instance and re-exports `LoadSource` and
        // `LoadError` from it; a second instance would be a second set of those
        // two types, and a consumer would name one while `load` expected the
        // other. `zig/root.zig` reaches for `rt` only in its linked arm, so
        // nothing here is referenced, resolved or compiled.
    } else {
        // Exactly one core instance for the two public types this SDK names in
        // either configuration. It costs a linked build two declarations and no
        // code, because nothing in that module is instantiated until a runtime
        // configuration asks for it. A second facade for the same target gets
        // this one rather than a second, because it publishes the same two
        // types under the same names.
        rt_core = if (reused) |previous|
            previous.rt_core.?
        else
            runtime_graph.createCoreModule(b, options.target, options.optimize);
        facade.addImport("rt", rt_core.?);
        if (artifact) |lib| {
            // The facade is the module every program of this build imports --
            // the example, each test binary, any dependent -- and every module
            // in a compilation's graph contributes its own rpaths, so the
            // search path is decided here, once, for every program built from
            // it. Which of the two paths that is belongs to `Loader`, and
            // `linkForLoader` says what each one is: the published module is
            // the `build_cache` one, because a dependent's executable is built
            // out of a build cache too. Only `bin/misuse` is built from an
            // `install_tree` facade, and it is built from a private one.
            linkForLoader(facade, lib, options.target, options.loader);
        } else {
            // The same search mode the translation line asked pkg-config about,
            // so the declarations and the library they bind to are one decision.
            facade.linkSystemLibrary(library_name, .{
                .use_pkg_config = .force,
                .preferred_link_mode = options.system_linkage,
            });
        }
    }

    return .{
        .module = facade,
        .artifact = artifact,
        .translate_c = translate_c,
        .rt_core = rt_core,
    };
}

/// The runtime search path an installed program needs so that its loader
/// finds the shared object this same prefix installed beside it.
///
/// `bin/misuse` and `lib/libSheenBidi.so` are siblings under one prefix, so
/// `$ORIGIN/../lib` is the ELF spelling and `@loader_path/../lib` the Mach-O
/// one, and both name this install tree and no other.  COFF has neither:
/// `installArtifact` puts `SheenBidi.dll` and its import library into `bin/`
/// beside the program, which is where its loader looks first.  A target with
/// no dynamic loader has nothing to name either.
fn installedProgramRPath(target: std.Build.ResolvedTarget) ?[]const u8 {
    return switch (target.result.os.tag) {
        .windows, .wasi, .uefi => null,
        else => if (target.result.os.tag.isDarwin()) "@loader_path/../lib" else "$ORIGIN/../lib",
    };
}

/// Where a program built against this SDK's shared library must find it.
///
/// The two are not two spellings of one answer, and one program cannot carry
/// both: `Module.linkLibrary` records the directory the shared object was
/// emitted into, because `Step.Compile` appends `-rpath <dir>` for every
/// dynamic artifact a compilation links (`lib/std/Build/Step/Compile.zig:1290-1297`,
/// the block reached from `.other_step`).  That directory is the build cache.
/// It does not exist once the file is installed, and Nix refuses an installed
/// file that names its own build directory at all, so an installed program
/// that carried it could never be packaged -- and on ELF the loader would
/// search a directory that is gone rather than the one that is there.
/// `Module.addObjectFile` puts the very same file on the link line and records
/// no search path at all, which leaves the relocatable entry
/// `installedProgramRPath` returns as the only one an installed artifact
/// carries.
///
/// Which of the two a facade gets is a property of the *program* that imports
/// it, and a published facade has dependents of both kinds. The entry a module
/// contributes lands on every compilation whose graph imports that module, so
/// the published `sheenbidi` module is `build_cache`: a dependent's executable
/// is built out of a build cache and finds the shared object in the one Zig
/// baked in. Only `bin/misuse` is built from an `install_tree` facade, and it
/// is built from a private one for that purpose.
const Loader = enum {
    /// A program `zig build install` writes into `bin/`.  It carries
    /// `$ORIGIN/../lib` -- `@loader_path/../lib` on Mach-O -- and nothing else,
    /// so it finds the library this prefix installed beside it and still finds
    /// it after the tree is moved.
    install_tree,
    /// Everything that is not installed, the published facade included: a
    /// dependent's executable, `smoke.zig`, a test binary, and the `check`
    /// matrix's compile-only copies.  It keeps the ordinary `linkLibrary` call,
    /// so Zig bakes in the directory the library really is in and the loader
    /// looks there.  The entry never reaches a store, because nothing built
    /// this way is ever installed.
    build_cache,
};

/// Put `library` on `module`'s link line, with the search path a program of
/// this `Loader` needs and nothing else.
fn linkForLoader(
    module: *std.Build.Module,
    library: *std.Build.Step.Compile,
    target: std.Build.ResolvedTarget,
    loader: Loader,
) void {
    // Windows links through the import library and has no rpath, so the
    // ordinary call is the right one there for both loaders and is kept.
    if (library.linkage != .dynamic or target.result.os.tag == .windows) {
        module.linkLibrary(library);
        return;
    }
    switch (loader) {
        .build_cache => module.linkLibrary(library),
        .install_tree => {
            module.addObjectFile(library.getEmittedBin());
            if (installedProgramRPath(target)) |rpath| module.addRPathSpecial(rpath);
        },
    }
}

/// Whether a target's programs have to be compiled twice to have both loaders.
///
/// A static archive, an import-library link on COFF and a facade that links no
/// library at all all produce the same file for both `Loader` values, so a
/// second graph would be a second copy of a binary that is already right.  A
/// shared library on a platform with a runpath is the one case where they
/// differ, and it is the only case that pays for the second compilation.
fn needsBothLoaders(
    linked: ?*std.Build.Step.Compile,
    target: std.Build.ResolvedTarget,
) bool {
    const library = linked orelse return false;
    return library.linkage == .dynamic and target.result.os.tag != .windows;
}

/// Whether `target` is this machine: the resolved host's architecture, operating
/// system and ABI. `Query.isNative()` cannot answer it — it is false for every
/// named target. Reasoning: section 4a of the delivery candidate.
fn isThisMachine(b: *std.Build, target: std.Build.ResolvedTarget) bool {
    const machine = &b.graph.host.result;
    return target.result.cpu.arch == machine.cpu.arch and
        target.result.os.tag == machine.os.tag and
        target.result.abi == machine.abi;
}

/// Compiles the C library, the facade, the test binary and the example for one
/// target, and attaches every one of them to `step`.
///
/// Compiling the test binary is what makes this a real check of the facade
/// rather than of an unreferenced archive: Zig analyses a function body only
/// when something calls it, and the test root is required to reference every
/// public facade function, so building it analyses all of them for that target.
/// The full C source is compiled by the same graph. Nothing is run, so every
/// result here is compile evidence and not a claim that a cross-built binary
/// executed.
/// What every cell of the cross matrix agrees on. The target is the only thing
/// that varies from cell to cell, so it is the only parameter; the rest would
/// otherwise be a positional `bool` sitting between two link modes.
const CheckOptions = struct {
    linkage: std.builtin.LinkMode,
    use_system: bool,
    system_linkage: std.builtin.LinkMode,
    runtime: bool,
};

fn addTargetCheck(
    b: *std.Build,
    step: *std.Build.Step,
    query: std.Target.Query,
    optimize: std.builtin.OptimizeMode,
    options: CheckOptions,
) void {
    const cross_target = b.resolveTargetQuery(query);
    const graph = addGraph(b, .{
        .target = cross_target,
        .optimize = optimize,
        // The artifact kind `check` compiles is the kind that was asked for, so
        // `zig build check -Dlinkage=dynamic` is a real check of the shared
        // form rather than a second compile of the static one wearing its name.
        // No target in `check_targets` is skipped for it: if a target cannot
        // produce a shared object, the failure belongs to the gate that asks for
        // one, not to a matrix that quietly answers a different question.
        .linkage = options.linkage,
        .system_linkage = options.system_linkage,
        .use_system = options.use_system,
        .public = false,
        // The dispatch is generated per target from that target's own
        // translation, so the cross matrix compiles a dispatch six times rather
        // than once for the host and five times for nothing.
        .runtime = options.runtime,
    });

    const tests_mod = b.createModule(.{
        .root_source_file = b.path("tests.zig"),
        .target = cross_target,
        .optimize = optimize,
        .link_libc = true,
    });
    tests_mod.addImport("sheenbidi", graph.module);
    step.dependOn(&b.addTest(.{ .root_module = tests_mod }).step);

    const smoke_mod = b.createModule(.{
        .root_source_file = b.path("smoke.zig"),
        .target = cross_target,
        .optimize = optimize,
        .link_libc = true,
    });
    smoke_mod.addImport("sheenbidi", graph.module);
    step.dependOn(&b.addExecutable(.{
        .name = "sheenbidi-smoke-cross",
        .root_module = smoke_mod,
    }).step);
}

/// Installs `lib/pkgconfig/SheenBidi.pc`, the one piece of consumer-facing
/// metadata this build owns.
///
/// Upstream ships `sheenbidi.pc.in`, and this file is that template with
/// exactly one value changed. Field names, field order, `Name`, `Description`,
/// `URL` and the `Libs:` spelling are upstream's (`sheenbidi.pc.in:5-10`, and
/// `meson.build:389-397`, which generates the same file with the same field
/// values), so a consumer of this install reads the record upstream's own
/// install produces.
///
/// The value that differs is `prefix`. Upstream writes CMake's configured
/// `@CMAKE_INSTALL_PREFIX@` (`sheenbidi.pc.in:1`), an absolute path frozen
/// when the file was generated; this build never fixes a prefix, so writing
/// one here would make the file wrong for every prefix but the one it happened
/// to be built with. It is written relative to the `.pc` file itself as
/// `${pcfiledir}/../..`, and pkg-config resolves `${pcfiledir}` against the
/// file it found, so `exec_prefix`, `libdir` and `includedir` follow the tree
/// rather than a build-time guess. That is this repository's established
/// convention and not an invention here: `blake3/build.zig:1115-1118`,
/// `box2d/build.zig:1400-1403`, `box3d/build.zig:1290-1293`,
/// `geographiclib-c/build.zig:999-1002` and
/// `fast_float/build_support/graph.zig:592-595` write those same four lines.
///
/// `Libs:` is upstream's literal line (`sheenbidi.pc.in:9`) in both linkages,
/// because the library *name* does not change with linkage: a C consumer asks
/// for `-lSheenBidi` and the linker resolves it to `libSheenBidi.a` or,
/// through the `libSheenBidi.so` symlink, to the shared object.
///
/// No per-target spelling of that line exists and none is invented here. On
/// Windows a dynamic build installs `SheenBidi.dll` beside the import library
/// that `-lSheenBidi` names, which is the same conclusion `addGraph` reaches
/// where it sets `.version` ("on Windows it is the import library name, which
/// is `SheenBidi.lib` either way"), so the one `Libs:` line is already the
/// COFF answer as well as the ELF one.
///
/// `Cflags:` carries `-I"${includedir}"` and, for a shared build, one
/// definition. The definition is upstream's own: `CMakeLists.txt:123-127`
/// appends `-DSB_CONFIG_DLL_IMPORT` to `SHEENBIDI_PKGCONFIG_CFLAGS` whenever
/// `BUILDING_DLL`, which `CMakeLists.txt:39-42` makes `WIN32 AND
/// BUILD_SHARED_LIBS`. It is what `Headers/SheenBidi/SBBase.h:34-35` reads to
/// turn `SB_PUBLIC` into `__declspec(dllimport)`, so a shared install that
/// omitted it would hand a Windows consumer declarations describing an
/// ordinary object file rather than a DLL. It is written for every target and
/// not only for Windows, because `SBBase.h:30` reads the pair only under
/// `_WIN32` and the macro is inert everywhere else — the same reasoning
/// `blake3/build.zig:1132`, `box2d/build.zig:1418` and `box3d/build.zig:1313`
/// act on. A static build emits no definition at all, which is what
/// `SBBase.h:40-42` leaves `SB_PUBLIC` when neither macro is defined.
///
/// `SB_CONFIG_EXPERIMENTAL_TEXT_API` is deliberately absent, and that is
/// upstream's rule rather than an omission here: `CMakeLists.txt:118-122` puts
/// it in `SHEENBIDI_PKGCONFIG_CFLAGS` only under `BUILD_TEXT_API`, and this
/// build does not build the text API (see the module comment). A `.pc` that
/// advertised it would describe declarations the installed archive does not
/// have, which is the failure this repository's `Cflags` are supposed to
/// prevent.
///
/// There is no `Libs.private:` line, because the compiled closure has nothing
/// private in it. Every symbol the core references outside its own translation
/// unit is a C library entry point, and every one of them is a symbol a
/// consumer's own `-lc` already provides:
///
///   * `malloc`, `realloc`, `free` — `Source/API/SBAllocator.c:174-184`.
///   * `memmove`, `memcpy`, `memcmp`, `qsort` — `Source/Core/List.c:113,144,183,197`.
///   * `memcmp` — `Source/API/SBAttributeInfo.h:52`.
///   * `strcmp`, `strlen`, `strcpy`, `qsort`, `bsearch` —
///     `Source/API/SBAttributeRegistry.c:35,43,54,161-176,200` and
///     `Source/API/SBText.c:167`.
///   * `memcpy` — `Source/API/SBText.c:266-916`, the text API's own copies.
///   * `assert` — `Source/API/SBAssert.h:20-22`, reached from fifteen units.
///   * `printf` — `Source/API/SBLog.h:22-45` and only under `SB_CONFIG_LOG`,
///     which `Headers/SheenBidi/SBConfig.h:22` ships commented out and
///     `c_flags` does not define. It is a libc symbol either way, which is
///     the only reason it is worth naming here.
///
/// No public header declares or calls any of them, so nothing in this library's
/// interface requires a consumer to link anything itself. Naming a
/// `Libs.private:` entry that the compiled closure does not have is how a
/// pkg-config record starts lying, and `pkg-config --static` would hand it to
/// every consumer of a shared install as well.
///
/// Two candidates were checked and neither is real, which is worth recording
/// because both are the usual answer for a C library:
///
///   * `-lm`. Nothing in `Source/` or `Headers/` includes `<math.h>` or names
///     a math function. The algorithm is integer classification, checked-in
///     table lookup and run reordering, and the unity unit that pulls in all
///     thirty-two of them (`Source/SheenBidi.c:17-58`) includes no `<math.h>`
///     either. There is no libm to name.
///   * `-lpthread` and `-latomic`. Both are reachable only through the
///     fallback arms of `Source/Core/ThreadLocalStorage.h:41-56` and
///     `Source/Core/AtomicPointer.h:36-50`, and no target this graph builds
///     selects one. `-std=c90` sits below the C11 threshold in
///     `Source/API/SBBase.h:58`, so `USE_C11_ATOMICS` and
///     `USE_C11_THREAD_LOCAL` are never defined; `zig cc` is Clang, so
///     `SBBase.h:41-46` gives `CLANG_VERSION >= 301` and `>= 100`, selecting
///     `USE_ATOMIC_BUILTINS` and `USE_CLANG_THREAD_LOCAL`; and
///     `ThreadLocalStorage.h:57-65` then spells the storage `__thread` or
///     `__declspec(thread)`, neither of which is a library. `USE_PTHREAD_KEY`
///     and `USE_WIN_INTRINSICS` are what a toolchain without those builtins
///     would reach, and all six entries of `check_targets` compile with Clang.
///
/// `Requires:` is present and empty, for the same reason: nothing outside libc
/// is involved, and libc is not something pkg-config can express portably.
///
/// `b.getInstallStep().dependOn` is the line that makes the file real.
/// `addInstallFileWithDir` only *creates* the `Step.InstallFile` and attaches
/// it to nothing, so without that line the file is described by the build
/// graph and never reaches `--prefix` while `zig build` still exits zero —
/// an installed archive with no metadata, invisible to every other check in
/// this repository.
fn addPkgConfig(b: *std.Build, linkage: std.builtin.LinkMode) void {
    const pc = b.addWriteFiles().add(b.fmt("{s}.pc", .{library_name}), b.fmt(
        \\# Generated by build.zig from upstream's sheenbidi.pc.in. Field names,
        \\# order and values are upstream's; `prefix` is the one value that
        \\# differs, written relative to this file instead of as CMake's
        \\# configured @CMAKE_INSTALL_PREFIX@ so the installed metadata is
        \\# correct wherever --prefix put it. build.zig's addPkgConfig says what
        \\# every other value is and why there is no Libs.private.
        \\prefix=${{pcfiledir}}/../..
        \\exec_prefix=${{prefix}}
        \\libdir=${{prefix}}/lib
        \\includedir=${{prefix}}/include
        \\
        \\Name: {s}
        \\Description: SheenBidi is a lightweight, fast and stable implementation of the Unicode Bidirectional Algorithm.
        \\URL: https://github.com/Tehreer/SheenBidi
        \\Version: {f}
        \\
        \\Requires:
        \\Libs: -L"${{libdir}}" -l{s}
        \\Cflags: -I"${{includedir}}"{s}
        \\
    , .{
        library_name,
        upstream.version,
        library_name,
        // Upstream's own `SHEENBIDI_PKGCONFIG_CFLAGS` entry under `BUILDING_DLL`
        // (`CMakeLists.txt:126`); empty for a static build, because neither
        // DLL macro is read outside `_WIN32` (`Headers/SheenBidi/SBBase.h:30`).
        if (linkage == .dynamic) " -DSB_CONFIG_DLL_IMPORT" else "",
    }));
    const install_pc = b.addInstallFileWithDir(
        pc,
        .lib,
        b.fmt("pkgconfig/{s}.pc", .{library_name}),
    );
    b.getInstallStep().dependOn(&install_pc.step);
}

/// Installs the licence, notice and provenance records under
/// `share/licenses/sheenbidi/`.
///
/// The same files `installed_documents` puts under `document_dir`, at the place
/// a package's terms are looked for by name. Both directories keep every path
/// they had; this adds the second spelling.
///
/// These are copies of files already in this repository, byte for byte;
/// nothing is rewritten, merged or truncated on the way out. `b.installFile`
/// takes a repository path and attaches its own step to the install step
/// (`lib/std/Build.zig:1675-1677`), so this needs no separate `dependOn` —
/// which is why the list above, and not a directory copy, is what makes the
/// install complete: a missing entry is a build failure naming the file.
fn installLicenceRecords(b: *std.Build) void {
    for (licence_records) |record| {
        b.installFile(record, b.pathJoin(&.{ licence_dir, std.fs.path.basename(record) }));
    }
}

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const use_system = b.systemIntegrationOption("sheenbidi", .{
        // Bundled by default. A distro package of SheenBidi is very unlikely
        // to be the 3.0.0 this manifest pins, and translating a header from one
        // release against a library from another is the silent-wrong-answer
        // failure this workspace forbids. Selecting the system library is a
        // decision a user makes on purpose with `-fsys=sheenbidi`.
        .default = false,
    });
    const linkage_option = b.option(
        std.builtin.LinkMode,
        "linkage",
        "Build the SheenBidi artifact statically or dynamically. Static is this " ++
            "package's existing default and installs libSheenBidi.a; dynamic " ++
            "installs a shared library with upstream's SONAME and compatibility " ++
            "names. In -fsys=sheenbidi mode this graph builds no artifact at " ++
            "all, so there the option names the kind of installed library to " ++
            "bind to instead, and both the linker search mode and the " ++
            "SB_CONFIG_DLL_IMPORT decoration follow it.",
    );
    // The kind of artifact this graph compiles. Static, because that is what
    // this package has always produced and an SDK's existing linkage policy is
    // not changed by the arrival of a second option.
    const linkage = linkage_option orelse @as(std.builtin.LinkMode, .static);
    // The kind of installed library `-fsys=sheenbidi` binds to. Defaulted to
    // dynamic rather than to `linkage`, because `linkage` describes artifacts
    // compiled out of this repository's own `Source/` and system mode compiles
    // none; `Module.linkSystemLibrary` prefers dynamic when the option is not
    // passed at all (`lib/std/Build/Module.zig:359`), so naming this default
    // changes what a default system build links by nothing at all.
    const system_linkage = linkage_option orelse std.builtin.LinkMode.dynamic;
    // Whether the facade resolves SheenBidi through the platform loader or
    // through the linker. Default false, which is the only configuration this
    // SDK has shipped, and orthogonal to `-Dlinkage`: that option says what is
    // compiled and installed, this one says what the facade is bound to. A
    // runtime build still compiles and installs the same artifact, it simply
    // does not link it, and a provider to `load` comes from wherever the caller
    // has one - which is why the two are separate knobs and neither rewrites
    // the other.
    const runtime = b.option(
        bool,
        "runtime",
        "Resolve SheenBidi's symbols through the platform loader instead of " ++
            "linking the library. Off by default. In this configuration `c` is a " ++
            "dispatch generated from this build's own translation output, the " ++
            "facade is not linked against libSheenBidi, and a caller must call " ++
            "`sheenbidi.load(.{ .path = ... })` before any other call.",
    ) orelse false;

    const package_version = std.SemanticVersion.parse(manifest.version) catch {
        @panic("build.zig.zon: .version is not a semantic version");
    };
    if (package_version.order(upstream.version) != .eq) {
        @panic("build.zig.zon .version no longer matches the pinned upstream release");
    }

    // `-fsys=sheenbidi` names a library installed on this machine, so it can only
    // mean a target this machine is.
    if (use_system and !isThisMachine(b, target)) {
        @panic("-fsys=sheenbidi names a library installed on this machine; it has no meaning for a foreign -Dtarget");
    }

    // Registered up front so `dep.module("sheenbidi")` resolves for dependents.
    const graph = addGraph(b, .{
        .target = target,
        .optimize = optimize,
        .linkage = linkage,
        .system_linkage = system_linkage,
        .use_system = use_system,
        .public = true,
        .runtime = runtime,
    });
    if (graph.artifact) |lib| b.installArtifact(lib);

    // The licence, attribution and integrity closure. Apache-2.0 requires the
    // licence text and the copyright notice to travel with the work, and the
    // eleven Unicode files are separately licensed material whose terms are
    // inside the files, so a recipient of a bare `libSheenBidi.a` could not
    // comply from this package alone. In `-fsys=sheenbidi` mode nothing is
    // installed, because nothing of ours was produced: the installed library
    // carries the closure of whichever package installed it.
    if (graph.artifact != null) {
        for (installed_documents) |document| {
            b.installFile(document, b.pathJoin(&.{ document_dir, std.fs.path.basename(document) }));
        }
        const unicode_dir = b.pathJoin(&.{ document_dir, "unicode" });
        for (installed_unicode_data) |data_file| {
            const dest = b.pathJoin(&.{ unicode_dir, std.fs.path.basename(data_file) });
            b.installFile(data_file, dest);
        }

        // The same records again, under the name a package's terms are looked
        // up by. `share/doc/sheenbidi/` keeps every path it had; this is the
        // second spelling, not a move.
        installLicenceRecords(b);

        // `lib/pkgconfig/SheenBidi.pc`, from the same install and gated on the
        // same condition. It is the only file in this graph that tells a C
        // consumer how to find what the rest of the install put there, and its
        // absence is invisible to every other check in this repository: an
        // archive with no metadata still compiles, still installs and still
        // links, and a consumer that hand-writes `-I` and `-lSheenBidi` works
        // right up until the prefix is not the one it assumed.
        addPkgConfig(b, linkage);
    }

    // The one installed program is `bin/misuse`, and the example is only
    // compiled. `zig build` compiles the example as well -- it is the cheapest
    // thing that proves the facade and the C agree on types, symbols and
    // link-time dependencies -- but it is not installed: it is a proof, not a
    // deliverable, and `installArtifact` is what would make it one. Out of the
    // build cache there is no `lib/` beside the binary, and an
    // `$ORIGIN/../lib` would name a directory the example does not have, so it
    // is built against the published facade, which carries the entry `linkLibrary`
    // bakes in from the directory the shared object really was emitted into.
    // The same is true of every dependent: its executable is built in a build
    // cache of its own, which is why the published facade has to be that
    // flavour rather than the installed one.
    //
    // `needsBothLoaders` is what decides whether `misuse` needs a facade of its
    // own: under `-Dlinkage=static`, under `-fsys=sheenbidi` and under
    // `-Druntime=true` both flavours produce the same file, and the graph
    // registered above is used as it stands.
    const install_facade = if (needsBothLoaders(if (runtime) null else graph.artifact, target))
        addGraph(b, .{
            .target = target,
            .optimize = optimize,
            .linkage = linkage,
            .system_linkage = system_linkage,
            .use_system = use_system,
            .public = false,
            .runtime = runtime,
            // The only `install_tree` facade in this graph: it exists so that
            // the one installed program finds the library this prefix installed
            // beside it. `public = false` keeps it from displacing the published
            // `sheenbidi` module a dependent reaches.
            .loader = .install_tree,
            // The same library, the same translation step and the same loader
            // core as the graph above; only the search path differs.
            .shared = &graph,
        }).module
    else
        graph.module;
    const smoke_mod = b.createModule(.{
        .root_source_file = b.path("smoke.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    smoke_mod.addImport("sheenbidi", graph.module);
    const smoke = b.addExecutable(.{
        .name = "sheenbidi-smoke",
        .root_module = smoke_mod,
    });
    b.getInstallStep().dependOn(&smoke.step);

    // The one observation a test binary cannot make about itself. `runtime/
    // misuse.zig` calls into the facade before any load, after a real load, and
    // once on a linked build; the first is expected to stop the process and the
    // second is the control that says the first stop was the loader's and not a
    // build that is broken for some other reason. It is built in both
    // configurations and installed, because a program nobody can run is not a
    // check, and being the only installed program it is also the only one built
    // from the install-tree flavour of the facade. Its doc comment names the
    // three invocations and nothing else about them is decided here.
    const misuse_mod = b.createModule(.{
        .root_source_file = b.path("runtime/misuse.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    misuse_mod.addImport("sheenbidi", install_facade);
    b.installArtifact(b.addExecutable(.{
        .name = "misuse",
        .root_module = misuse_mod,
    }));

    // A run artifact already depends on building the executable, which depends
    // on compiling the C and linking the facade. `zig build smoke` deliberately
    // does not run the install step: installing is `zig build`'s job, and
    // conflating the two would make a smoke run depend on the install layout.
    //
    // Nothing here names a provider, and that is deliberate rather than an
    // omission. `smoke.zig` and `tests.zig` each take the provider from
    // `SHEENBIDI_PROVIDER` or `--provider <path>` and stop with a message naming
    // the two when neither is set, so in a runtime configuration these steps
    // run and fail honestly instead of quietly testing something. Exporting the
    // variable here would be wrong for the other reason: a path this build did
    // not produce - there is none under `-Dlinkage=static` - would be a lie, and
    // naming one only when `dynamic` happens to be selected would make the step
    // mean two different things depending on a flag it is not about. A caller
    // runs `zig build` and then runs the binary with the provider it wants, the
    // same way `runtime/misuse.zig` is run.
    const smoke_step = b.step("smoke", "Run the deterministic example");
    const smoke_run = b.addRunArtifact(smoke);
    // A run whose inputs did not change is otherwise served from the run cache
    // and never executes, so a second `zig build smoke` over an unchanged tree
    // would report success without the program having observed anything. The
    // flag is what makes this step's result the program's own rather than a
    // replay of an earlier one.
    smoke_run.has_side_effects = true;
    if (b.args) |args| smoke_run.addArgs(args);
    smoke_step.dependOn(&smoke_run.step);

    // The test root is `tests.zig`, a plain module rooted at the package root
    // with the facade added as an import. It is not wrapped: a root that only
    // re-exported other files would discover no test blocks and still exit zero.
    const test_step = b.step("test", "Build and run the behavioral tests in Debug and ReleaseSafe");
    for (test_optimize_modes) |mode| {
        const mode_graph = addGraph(b, .{
            .target = target,
            .optimize = mode,
            .linkage = linkage,
            .system_linkage = system_linkage,
            .use_system = use_system,
            .public = false,
            .runtime = runtime,
        });
        const tests_mod = b.createModule(.{
            .root_source_file = b.path("tests.zig"),
            .target = target,
            .optimize = mode,
            .link_libc = true,
        });
        tests_mod.addImport("sheenbidi", mode_graph.module);
        const unit = b.addTest(.{ .root_module = tests_mod });
        const unit_run = b.addRunArtifact(unit);
        // The same reason as the smoke run above, and it matters more here: a
        // cached run would let a second `zig build test` over an unchanged tree
        // pass without a single assertion being evaluated.
        unit_run.has_side_effects = true;
        test_step.dependOn(&unit_run.step);
    }

    const check_step = b.step(
        "check",
        "Compile the C source, facade, tests and example for every supported target without running them",
    );
    const check_options: CheckOptions = .{
        .linkage = linkage,
        .use_system = use_system,
        .system_linkage = system_linkage,
        .runtime = runtime,
    };
    if (use_system) {
        // An installed SheenBidi is a library for this host, so there is nothing
        // for a cross target to bind to. `check` stays on the requested target
        // and says so, rather than reporting a green six-target matrix it never
        // looked at.
        addTargetCheck(b, check_step, target.query, optimize, check_options);
    } else if (!target.query.isNative()) {
        // An explicit `-Dtarget` is a question about that target, so `check`
        // answers it instead of also answering five questions nobody asked.
        addTargetCheck(b, check_step, target.query, optimize, check_options);
    } else {
        for (check_targets) |query| {
            addTargetCheck(b, check_step, query, optimize, check_options);
        }
    }
}
