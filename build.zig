//! SheenBidi 3.0.0 packaged for Zig 0.16.0.
//!
//! This build compiles the complete upstream core and publishes it as a Zig
//! package module named `sheenbidi`.
//!
//! What is compiled
//! ----------------
//! `Source/SheenBidi.c` is upstream's unity translation unit and this is
//! upstream's own default way to build the library: `meson_options.txt` says
//! `unity_mode = enabled` and `CMakeLists.txt` says
//! `option(SB_CONFIG_UNITY "Build with a single unity source file" ON)`. That
//! one file `#include`s every checked-in `.c` under `Source/`, so the archive
//! carries the whole library and not a hand-picked subset: the fifteen public
//! API units, the four core units, the four generated UCD tables, the script
//! stack, the two text-support units and the six UBA run units. The optional
//! text-API units are included by the unity file unconditionally and each is
//! internally wrapped in `#if SB_TEXT_API_SUPPORTED`, so with that macro off
//! they contribute no definitions, which is upstream's arrangement and not an
//! omission here.
//!
//! The list is deliberately one entry long. A glob or a per-file list would let
//! a translation unit be added to or dropped from the archive without a
//! decision, and unity is the only complete-source build upstream offers.
//!
//! Unicode data
//! ------------
//! No table is generated. `Source/Data/BidiTypeLookup.c`,
//! `GeneralCategoryLookup.c`, `PairingLookup.c` and `ScriptLookup.c` are
//! checked-in tables generated by upstream's own `Tools/Generator` from UCD
//! 17.0.0, and they are compiled byte-for-byte unchanged. `Tools/` keeps the
//! UCD inputs, the parser and the generator, and is preserved in this
//! repository for provenance, so the tables can be regenerated deliberately and
//! so the Unicode data terms those inputs carry travel with the package; no
//! step of this build runs any of `Tools/Generator` or `Tools/Parser`, and
//! nothing is downloaded.
//!
//! Configuration
//! -------------
//! The library is built with `SB_CONFIG_UNITY` and without
//! `SB_CONFIG_EXPERIMENTAL_TEXT_API`, which is the configuration upstream ships
//! as the default: `Headers/SheenBidi/SBConfig.h:39` ships the macro commented
//! out, `CMakeLists.txt:18` defaults the option OFF and `meson_options.txt`
//! disables the text API. Atomics and thread-local storage are left to the
//! source's own feature detection: `SB_CONFIG_ALLOW_NON_ATOMIC_FALLBACK` is not
//! defined, so a threaded target gets real atomics rather than a silent
//! non-atomic fallback. The consequences of the chosen C dialect are spelled
//! out next to `c_flags`.
//!
//! That is one decision applied on both sides of the boundary. The experimental
//! text API is absent from the C compile line *and* from the translation line
//! in every mode, so the declarations the facade can name and the definitions
//! the archive holds are the same set. With the macro off,
//! `Headers/SheenBidi/SBBase.h:44-48` makes `SB_TEXT_API_SUPPORTED` 0 and the
//! bodies of `SBText.h`, `SBTextConfig.h` and `SBTextIterators.h` expand to
//! nothing, so `zig/translate.h` does not declare them and the archive does not
//! define them. It is absent from the selected configuration, and nothing in
//! this package stubs either half of it.
//!
//! Linkage
//! -------
//! `-Dlinkage=static` is the default and is what this package has always
//! produced: `libSheenBidi.a`. `-Dlinkage=dynamic` produces a shared library
//! with the version and compatibility names upstream's own install produces
//! (`CMakeLists.txt:143-147` sets `VERSION ${PROJECT_VERSION}` and
//! `SOVERSION ${PROJECT_VERSION_MAJOR}`), so `-lSheenBidi` resolves the same
//! way against either artifact.
//!
//! `static` names the artifact kind and nothing more. It is not a promise of a
//! wholly static executable: SheenBidi calls `malloc`, `free`, `memcpy` and
//! `memmove` (`Source/API/SBAllocator.c`, `Source/Core/Memory.c`), so every
//! module in this graph sets `link_libc = true` in both linkages.
//!
//! Exports
//! -------
//! SheenBidi has exactly one export mechanism and it is upstream's own:
//! `Headers/SheenBidi/SBConfig.h:20-21` ships `SB_CONFIG_DLL_EXPORT` and
//! `SB_CONFIG_DLL_IMPORT` commented out, and
//! `Headers/SheenBidi/SBBase.h:30-42` reads them to decide what `SB_PUBLIC`
//! expands to. `-DSB_CONFIG_DLL_EXPORT` goes on the C compile line when, and
//! only when, the shared library is the thing being built, and
//! `-DSB_CONFIG_DLL_IMPORT` goes on the translation line when, and only when,
//! the declarations being translated are the ones a DLL provides. That is
//! upstream's own rule, stated at `CMakeLists.txt:123-127` for its
//! `BUILDING_DLL` case, and it is applied here as a compiler flag so that no
//! checked-in header is edited.
//!
//! Two consequences follow from the header and are stated rather than worked
//! around:
//!
//!   * `SB_PUBLIC` expands to `__declspec(dllexport)`/`(dllimport)` only under
//!     `_WIN32` (`Headers/SheenBidi/SBBase.h:30`). On ELF and macOS it expands
//!     to nothing, and this build therefore does **not** pass
//!     `-fvisibility=hidden`. A hidden-visibility shared library would export
//!     nothing at all, because there is no `visibility("default")` arm for the
//!     public names to take. What a POSIX shared object exports is instead
//!     every symbol that is not `static`, and unity mode is what bounds that
//!     set: `Source/API/SBBase.h:26-30` makes `SB_INTERNAL` `static` under
//!     `SB_CONFIG_UNITY`, so all 32 implementation units have internal
//!     linkage and only the `SB_PUBLIC` entry points remain external.
//!   * On Windows the `SB_CONFIG_DLL_IMPORT` arm is what makes a translation
//!     declare a symbol the way a caller declares one that a DLL provides;
//!     `zig translate-c` carries that through as `is_dll_import`
//!     (`lib/std/builtin.zig:1106`), so the decoration reaches the generated
//!     Zig rather than being discarded with the macro.
//!
//! Runtime route
//! -------------
//! `-Druntime=false` is the default and the only configuration this SDK has
//! shipped: the facade is linked against the library and `c` is the
//! translation step's own output. `-Druntime=true` replaces that `c` with a
//! dispatch generated from the same translation step's output
//! (`runtime/graph.zig`), drops the facade's native link, and makes
//! `sheenbidi.load(.{ .path = ... })` the call that makes the library usable.
//!
//! The two options are orthogonal and neither rewrites the other.
//! `-Dlinkage` still decides what is compiled and installed, including in a
//! runtime build; `-Druntime` only decides what the facade is bound to. A
//! runtime build therefore still installs `libSheenBidi.a` or
//! `libSheenBidi.so*` as `-Dlinkage` asked, and a caller loads a provider from
//! wherever it has one.
//!
//! Two things follow from that split and are load-bearing rather than
//! incidental. The linked build imports the reusable loader core once, as `rt`,
//! for the two public types it names; the runtime build does not import it at
//! all, because the dispatch owns the one instance and re-exports them, and two
//! instances would be two sets of types. And neither configuration registers
//! the dispatch under the graph name `c`, so `dep.module("c")` exists in a
//! linked build only - the name `zig/root.zig` itself calls wiring rather than a
//! second supported import.
//!
//! Installed closure
//! -----------------
//! `zig build` installs the artifact, all 23 public headers under
//! `include/SheenBidi/` (where upstream's own rule puts them,
//! `CMakeLists.txt:359-363`), the licence and provenance document set under
//! `share/doc/sheenbidi/`, the eleven Unicode data files under
//! `share/doc/sheenbidi/unicode/` and `lib/pkgconfig/SheenBidi.pc`. The
//! document set is the licence closure and not decoration: `LICENSE` is
//! upstream's Apache-2.0 text verbatim, `README.upstream.md` carries that grant
//! and the upstream copyright line
//! (`README.upstream.md:169-184` and `:171`), `NOTICE.md` carries the per-file
//! exceptions and the split between the Apache-2.0 tree and the separately
//! licensed Unicode files, `FORK-LICENSE.md` records the grant for this fork's
//! own files, and `UPSTREAM.sha256` is the record that binds the shipped
//! upstream bytes to their digests. Those records install a second time under
//! `share/licenses/sheenbidi/` - `LICENSE`, `README.upstream.md`,
//! `NOTICE.md`, `FORK-LICENSE.md`, `UPSTREAM.md`, `FORK-NOTES.md` and
//! `UPSTREAM.sha256` - which is the path a package's terms are looked up by and
//! the one every other package here uses; the eleven Unicode files stay under
//! `share/doc/sheenbidi/unicode/` only, because their terms are inside the
//! files. The eleven Unicode files are installed
//! unmodified, under the terms their own headers name, because those terms
//! reach a recipient only if the files do.
//!
//! pkg-config metadata is generated after all, by `addPkgConfig`, and is
//! upstream's own `sheenbidi.pc.in` with one value changed. Field names, field
//! order and values are upstream's; `prefix` is not, because upstream
//! substitutes CMake's configured `@CMAKE_INSTALL_PREFIX@` — an absolute path
//! frozen at configure time — and this build never fixes a prefix at all. It
//! is written here as `${pcfiledir}/../..`, relative to the `.pc` file itself,
//! so the installed file resolves against the tree pkg-config found it in and
//! is correct wherever `--prefix` put it. That is this repository's
//! established convention rather than an invention here; `blake3/build.zig:1115`,
//! `box2d/build.zig:1400`, `box3d/build.zig:1290`,
//! `fast_float/build_support/graph.zig:592` and
//! `geographiclib-c/build.zig:999` all write those same four lines.
//! `addPkgConfig` says what every other value in the file is, and why the file
//! has no `Libs.private:` line at all.
//!
//! Steps
//! -----
//!   zig build            install the library, the public headers, the
//!                        licence/provenance closure and
//!                        lib/pkgconfig/SheenBidi.pc, and compile smoke.zig
//!                        (not run)
//!   zig build test       build and run tests.zig in Debug and ReleaseSafe
//!   zig build smoke      run smoke.zig
//!   zig build check      compile-only: full C core, facade, tests and smoke for
//!                        each cross target, with every public facade method
//!                        instantiated
//!   zig build -Dlinkage=static|dynamic
//!                        choose which artifact kind is compiled and installed
//!   zig build -Druntime=true
//!                        build the same library and headers, but resolve the
//!                        facade's symbols through the platform loader
//!   zig build -fsys=sheenbidi
//!                        link an installed SheenBidi instead of building one
//!
//! `-fsys=sheenbidi` is spelled that way and not `-Dsystem=...` because
//! `b.systemIntegrationOption` writes to the build graph's system-library map,
//! which the build runner fills from `-fsys=` / `-fno-sys=`, never from the `-D`
//! option map. In that mode no archive of ours is produced and nothing is
//! installed; the facade and the translation both bind to the system library and
//! the system header. `-Dlinkage` names the kind of *installed* library to bind
//! to there, because in that mode this graph builds nothing: the linker search
//! mode and the `SB_CONFIG_DLL_IMPORT` decoration both follow it, so the
//! decoration cannot describe a different kind of library from the one the
//! linker is asked for.
