//! SheenBidi 3.0.0 packaged for Zig 0.16.0.
//!
//! This build compiles the complete upstream core and publishes it as a Zig
//! package module named `sheenbidi`.
//!
//! What is compiled
//! ----------------
//! `Source/SheenBidi.c` is upstream's unity translation unit and this is
//! upstream's own default way to build the library: `meson_options.txt` says
//! `unity_mode = enabled` and `CMakeLists.txt` says
//! `option(SB_CONFIG_UNITY "Build with a single unity source file" ON)`. That
//! one file `#include`s every checked-in `.c` under `Source/`, so the archive
//! carries the whole library and not a hand-picked subset: the fifteen public
//! API units, the four core units, the four generated UCD tables, the script
//! stack, the two text-support units and the six UBA run units. The optional
//! text-API units are included by the unity file unconditionally and each is
//! internally wrapped in `#if SB_TEXT_API_SUPPORTED`, so with that macro off
//! they contribute no definitions, which is upstream's arrangement and not an
//! omission here.
//!
//! The list is deliberately one entry long. A glob or a per-file list would let
//! a translation unit be added to or dropped from the archive without a
//! decision, and unity is the only complete-source build upstream offers.
//!
//! Unicode data
//! ------------
//! No table is generated. `Source/Data/BidiTypeLookup.c`,
//! `GeneralCategoryLookup.c`, `PairingLookup.c` and `ScriptLookup.c` are
//! checked-in tables generated by upstream's own `Tools/Generator` from UCD
//! 17.0.0, and they are compiled byte-for-byte unchanged. `Tools/` keeps the
//! UCD inputs, the parser and the generator, and is preserved in this
//! repository for provenance and so the tables can be regenerated deliberately;
//! no step of this build runs any of it, and nothing is downloaded.
//!
//! Configuration
//! -------------
//! The library is built with `SB_CONFIG_UNITY` and without
//! `SB_CONFIG_EXPERIMENTAL_TEXT_API`, which is the configuration upstream ships
//! as the default. Atomics and thread-local storage are left to the source's own
//! feature detection: `SB_CONFIG_ALLOW_NON_ATOMIC_FALLBACK` is not defined, so
//! a threaded target gets real atomics rather than a silent non-atomic fallback.
//! The consequences of the chosen C dialect are spelled out next to `c_flags`.
//!
//! Steps
//! -----
//!   zig build            install the static archive and the public headers, and
//!                        compile smoke.zig (not run)
//!   zig build test       build and run tests.zig in Debug and ReleaseSafe
//!   zig build smoke      run smoke.zig
//!   zig build check      compile-only: full C core, facade, tests and smoke for
//!                        each cross target, with every public facade method
//!                        instantiated
//!   zig build -fsys=sheenbidi
//!                        link an installed SheenBidi instead of building one
//!
//! `-fsys=sheenbidi` is spelled that way and not `-Dsystem=...` because
//! `b.systemIntegrationOption` writes to the build graph's system-library map,
//! which the build runner fills from `-fsys=` / `-fno-sys=`, never from the `-D`
//! option map. In that mode no archive of ours is produced and nothing is
//! installed; the facade and the translation both bind to the system library and
//! the system header.

const std = @import("std");

const manifest = @import("build.zig.zon");

/// Identity of the upstream release this package carries.
const upstream = struct {
    const canonical_url = "https://github.com/Tehreer/SheenBidi.git";
    const commit = "cfe430e7375a7845b679adae9d51dac6deaa8858";
    const version: std.SemanticVersion = .{ .major = 3, .minor = 0, .patch = 0 };
    /// UCD revision the checked-in `Source/Data` tables were generated from.
    const unicode_version = "17.0.0";
};

/// The complete core: upstream's unity unit and nothing else.
const core_source = "Source/SheenBidi.c";

/// Public headers. Installed to `include/SheenBidi/<name>.h`, which is where
/// upstream's own install rule puts them
/// (`PUBLIC_HEADER DESTINATION "${CMAKE_INSTALL_INCLUDEDIR}/SheenBidi"`), so the
/// directory is named once and never nested inside itself.
const public_header_source = "Headers/SheenBidi";
const public_header_dest = "SheenBidi";

/// The name of the installed library, used for the archive this build produces
/// and for the library `-fsys=sheenbidi` links. It is capitalised because that
/// is the name upstream installs: `libSheenBidi.a` / `libSheenBidi.so`, with
/// `Libs: -L${libdir} -lSheenBidi` in sheenbidi.pc.in. A lowercase name would
/// ask the linker for a `libsheenbidi` that no install of this library creates.
const library_name = "SheenBidi";

/// Flags for the one C translation unit.
///
/// `-std=c90` pins the dialect to the level upstream actually builds and tests
/// this source at, rather than to whatever the compiler happens to default to.
/// All three of upstream's build systems say the same thing: `Makefile` passes
/// `-ansi -pedantic`, `.github/workflows/linux.yml` passes
/// `CMAKE_C_STANDARD=90` with `CMAKE_C_EXTENSIONS=OFF` and `-Dc_std=c89` to
/// meson. It is not cosmetic. `Source/API/SBBase.h` and
/// `Source/Core/ThreadLocalStorage.h` select their atomics and TLS backend from
/// `__STDC_VERSION__`, and the choice decides which headers get pulled in: at
/// C11 and above they take the `USE_C11_*` branches and `#include <stdatomic.h>`,
/// while below it they fall through to the compiler-builtin branches
/// (`__atomic_*` and `__thread`) that need no standard or platform header at
/// all. Pinning the dialect is what keeps that decision deterministic across
/// the six targets this package claims.
///
/// `-DSB_CONFIG_UNITY` is upstream's unity switch. It is what turns
/// `SB_INTERNAL` into `static` so the thirty-two included translation units merge
/// into one without a single name colliding, and it is what makes
/// `Source/SheenBidi.c` a translation unit at all.
///
/// `SB_CONFIG_EXPERIMENTAL_TEXT_API` is absent on purpose, and so is
/// `SB_CONFIG_ALLOW_NON_ATOMIC_FALLBACK`: forcing the non-atomic path on a
/// threaded target would make a data race compile cleanly.
const c_flags = [_][]const u8{
    "-std=c90",
    "-DSB_CONFIG_UNITY",
};

/// The targets `check` analyses when no `-Dtarget` was given. Every one is
/// attempted; none is skipped or quietly dropped.
const check_targets = [_]std.Target.Query{
    .{ .cpu_arch = .x86_64, .os_tag = .linux, .abi = .gnu },
    .{ .cpu_arch = .aarch64, .os_tag = .linux, .abi = .gnu },
    .{ .cpu_arch = .aarch64, .os_tag = .macos, .abi = .none },
    .{ .cpu_arch = .x86_64, .os_tag = .windows, .abi = .gnu },
    .{ .cpu_arch = .riscv64, .os_tag = .linux, .abi = .gnu },
    .{ .cpu_arch = .wasm32, .os_tag = .wasi },
};

/// The modes `test` runs in. Both are the modes where Zig's own safety checks
/// are live, so a facade bug shows up in one of them and not the other.
/// `-Doptimize` still selects the mode of the default graph, the example and
/// `check`; it does not narrow this step, which is why the two commands in
/// AGENTS.md cannot differ in what they prove.
const test_optimize_modes = [_]std.builtin.OptimizeMode{ .Debug, .ReleaseSafe };

/// Everything one target needs: the facade module, and the C archive when this
/// build owns one.
const Graph = struct {
    /// The facade, with `c` bound to the translated aggregate header.
    module: *std.Build.Module,
    /// Null in `-fsys=sheenbidi` mode, where the library comes from the system.
    artifact: ?*std.Build.Step.Compile,
};

/// Builds the C library and the facade for one target.
///
/// `public` chooses between the package module set, which is what a dependent
/// reaches through `dep.module("sheenbidi")`, and a private module. The cross
/// target check needs the private form: modules are registered by name against
/// the whole build, so registering `sheenbidi` and `c` once per cross target
/// would leave only the last pair reachable and silently stop checking the rest.
fn addGraph(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    use_system: bool,
    public: bool,
) Graph {
    var artifact: ?*std.Build.Step.Compile = null;

    if (!use_system) {
        const c_mod = b.createModule(.{
            .target = target,
            .optimize = optimize,
            // libc, because the core includes <stddef.h>, <stdlib.h>,
            // <string.h> and, through <SheenBidi/SBBase.h>, <stdint.h>.
            .link_libc = true,
        });
        // `Headers` answers the <SheenBidi/...> includes; `Source` answers the
        // <API/...>, <Core/...>, <Data/...>, <Script/...>, <Text/...> and
        // <UBA/...> includes that the unity unit performs with angle brackets.
        c_mod.addIncludePath(b.path("Headers"));
        c_mod.addIncludePath(b.path("Source"));
        c_mod.addCSourceFile(.{
            .file = b.path(core_source),
            .flags = &c_flags,
        });

        const lib = b.addLibrary(.{
            .name = library_name,
            .linkage = .static,
            .root_module = c_mod,
        });
        // Installing the headers also puts them on the include search path of
        // anything that links this artifact, so a dependent that wants the C
        // API does not have to reach into this repository's tree for it.
        lib.installHeadersDirectory(b.path(public_header_source), public_header_dest, .{});
        artifact = lib;
    }

    const translate_c = b.addTranslateC(.{
        .root_source_file = b.path("zig/translate.h"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    if (use_system) {
        // No bundled include path, so <SheenBidi/SheenBidi.h> resolves to the
        // installed header. pkg-config is asked first because sheenbidi.pc
        // carries both the `-I` for a non-standard prefix and the capitalised
        // `-lSheenBidi`; without it the plain library name is still right,
        // because that is the name upstream installs.
        translate_c.linkSystemLibrary(library_name, .{ .use_pkg_config = .yes });
    } else {
        translate_c.addIncludePath(b.path("Headers"));
    }
    const raw = if (public) translate_c.addModule("c") else translate_c.createModule();

    const facade = if (public)
        b.addModule("sheenbidi", .{
            .root_source_file = b.path("zig/root.zig"),
            .target = target,
            .optimize = optimize,
            .link_libc = true,
        })
    else
        b.createModule(.{
            .root_source_file = b.path("zig/root.zig"),
            .target = target,
            .optimize = optimize,
            .link_libc = true,
        });
    facade.addImport("c", raw);
    if (artifact) |lib| {
        facade.linkLibrary(lib);
    } else {
        facade.linkSystemLibrary(library_name, .{ .use_pkg_config = .yes });
    }

    return .{ .module = facade, .artifact = artifact };
}

/// Compiles the C library, the facade, the test binary and the example for one
/// target, and attaches every one of them to `step`.
///
/// Compiling the test binary is what makes this a real check of the facade
/// rather than of an unreferenced archive: Zig analyses a function body only
/// when something calls it, and the test root is required to reference every
/// public facade function, so building it analyses all of them for that target.
/// The full C source is compiled by the same graph. Nothing is run, so every
/// result here is compile evidence and not a claim that a cross-built binary
/// executed.
fn addTargetCheck(
    b: *std.Build,
    step: *std.Build.Step,
    query: std.Target.Query,
    optimize: std.builtin.OptimizeMode,
    use_system: bool,
) void {
    const cross_target = b.resolveTargetQuery(query);
    const graph = addGraph(b, cross_target, optimize, use_system, false);

    const tests_mod = b.createModule(.{
        .root_source_file = b.path("tests.zig"),
        .target = cross_target,
        .optimize = optimize,
        .link_libc = true,
    });
    tests_mod.addImport("sheenbidi", graph.module);
    step.dependOn(&b.addTest(.{ .root_module = tests_mod }).step);

    const smoke_mod = b.createModule(.{
        .root_source_file = b.path("smoke.zig"),
        .target = cross_target,
        .optimize = optimize,
        .link_libc = true,
    });
    smoke_mod.addImport("sheenbidi", graph.module);
    step.dependOn(&b.addExecutable(.{
        .name = "sheenbidi-smoke-cross",
        .root_module = smoke_mod,
    }).step);
}

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const use_system = b.systemIntegrationOption("sheenbidi", .{
        // Bundled by default. A distro package of SheenBidi is very unlikely
        // to be the 3.0.0 this manifest pins, and translating a header from one
        // release against a library from another is the silent-wrong-answer
        // failure this workspace forbids. Selecting the system library is a
        // decision a user makes on purpose with `-fsys=sheenbidi`.
        .default = false,
    });

    const package_version = std.SemanticVersion.parse(manifest.version) catch {
        @panic("build.zig.zon: .version is not a semantic version");
    };
    if (package_version.order(upstream.version) != .eq) {
        @panic("build.zig.zon .version no longer matches the pinned upstream release");
    }

    // Registered up front so `dep.module("sheenbidi")` resolves for dependents.
    const graph = addGraph(b, target, optimize, use_system, true);
    if (graph.artifact) |lib| b.installArtifact(lib);

    // `zig build` compiles the example as well. The example is the cheapest
    // thing that proves the facade and the C agree on types, symbols and
    // link-time dependencies. It is not installed: it is a proof, not a
    // deliverable.
    const smoke_mod = b.createModule(.{
        .root_source_file = b.path("smoke.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    smoke_mod.addImport("sheenbidi", graph.module);
    const smoke = b.addExecutable(.{
        .name = "sheenbidi-smoke",
        .root_module = smoke_mod,
    });
    b.getInstallStep().dependOn(&smoke.step);

    // A run artifact already depends on building the executable, which depends
    // on compiling the C and linking the facade. `zig build smoke` deliberately
    // does not run the install step: installing is `zig build`'s job, and
    // conflating the two would make a smoke run depend on the install layout.
    const smoke_step = b.step("smoke", "Run the deterministic example");
    smoke_step.dependOn(&b.addRunArtifact(smoke).step);

    // The test root is `tests.zig`, a plain module rooted at the package root
    // with the facade added as an import. It is not wrapped: a root that only
    // re-exported other files would discover no test blocks and still exit zero.
    const test_step = b.step("test", "Build and run the behavioral tests in Debug and ReleaseSafe");
    for (test_optimize_modes) |mode| {
        const mode_graph = addGraph(b, target, mode, use_system, false);
        const tests_mod = b.createModule(.{
            .root_source_file = b.path("tests.zig"),
            .target = target,
            .optimize = mode,
            .link_libc = true,
        });
        tests_mod.addImport("sheenbidi", mode_graph.module);
        test_step.dependOn(&b.addRunArtifact(b.addTest(.{ .root_module = tests_mod })).step);
    }

    const check_step = b.step(
        "check",
        "Compile the C source, facade, tests and example for every supported target without running them",
    );
    if (use_system) {
        // An installed SheenBidi is a library for this host, so there is nothing
        // for a cross target to bind to. `check` stays on the requested target
        // and says so, rather than reporting a green six-target matrix it never
        // looked at.
        addTargetCheck(b, check_step, target.query, optimize, true);
    } else if (!target.query.isNative()) {
        // An explicit `-Dtarget` is a question about that target, so `check`
        // answers it instead of also answering five questions nobody asked.
        addTargetCheck(b, check_step, target.query, optimize, false);
    } else {
        for (check_targets) |query| addTargetCheck(b, check_step, query, optimize, false);
    }
}
